#!/bin/sh
set -eu

XBOX360_IP="${XBOX360_IP:-192.168.0.162}"
XBOX360_POLL_INTERVAL="${XBOX360_POLL_INTERVAL:-30}"
XBOX360_VERBOSE="${XBOX360_VERBOSE:-0}"
XBOX360_ENABLED="${XBOX360_ENABLED:-false}"
TMDB_API_KEY="${TMDB_API_KEY:-}"

CONFIG_PATH="${CONFIG_PATH:-/app/xbdStats.ini}"

cat > "$CONFIG_PATH" <<EOF
[Xbox360]
IP=$XBOX360_IP
PollInterval=$XBOX360_POLL_INTERVAL
Verbose=$XBOX360_VERBOSE
Enabled=$XBOX360_ENABLED
[media]
tmdb_api_key=$TMDB_API_KEY
EOF

exec /app/xbdStats "$@"